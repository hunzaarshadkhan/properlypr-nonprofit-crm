import assert from "node:assert/strict";
import { parseCSV, autoMap, csvDocument } from "../csv.js";
import { openDatabase } from "../dev/database.mjs";
import app from "../dist/server/index.js";
import { transition } from "../workflow.js";

const db = openDatabase(":memory:");
const env = { DB:db };
async function call(path, data, authenticated = true) {
  const r = await app.fetch(new Request("https://crm.example" + path, {method:"POST", headers:{"Content-Type":"application/json", Origin:"https://crm.example", ...(authenticated ? {"oai-authenticated-user-id":"csv-rep"} : {})}, body:JSON.stringify(data)}), env);
  return { status:r.status, data:r.headers.get("Content-Type").includes("text/csv") ? await r.text() : await r.json() };
}
const text = '\uFEFFNonprofit,EIN,Person name,Phone,Domain,Published email candidate,Research notes\r\n"Fictional, Foundation",01-2345678,Test Person,+15555550101,example.org,candidate@example.org,"First line\r\nSecond ""quoted"" line"\r\nOther Fictional,987654321,Other Person,5555550102,other.example,,\r\n';
const parsed = parseCSV(text), mapping = autoMap(parsed.headers);
assert.equal(parsed.rows.length, 2);
assert.equal(parsed.rows[0][6], 'First line\r\nSecond "quoted" line');
assert.equal(mapping.contact, "2");
assert.equal(mapping.candidate, "5");
assert.equal(mapping.email, "");
assert.throws(() => parseCSV('Name,EIN\na,"unterminated'), /closing quote/);
assert.throws(() => parseCSV('Name,name\na,b'), /unique/);
assert.throws(() => parseCSV('Name,EIN\na,b,c'), /same number/);
assert.throws(() => parseCSV('Name,EIN\n"closed"oops,123'), /quoting/);
assert.throws(() => parseCSV('Name,EIN\n' + 'a,123\n'.repeat(1001)), /1,000/);
assert.equal(autoMap(["Email", "Working email"]).email, "");
const payload = {text, mapping, destination:"First call", filename:"fixture.csv", requestId:crypto.randomUUID()};
assert.equal((await call("/api/csv/preview", payload, false)).status, 401);
assert.equal((await call("/api/csv/import", payload, false)).status, 401);
let res = await call("/api/csv/preview", payload);
assert.equal(res.data.ready, 2);
assert.equal(db.prepare("SELECT COUNT(*) AS n FROM organizations").first().n, 0, "preview must not write");
res = await call("/api/csv/import", payload);
assert.equal(res.data.added, 2);
let org = JSON.parse(db.prepare("SELECT profile FROM organizations WHERE id=?").bind("012345678").first().profile);
assert.equal(org.name, "Fictional, Foundation");
assert.equal(org.email, undefined, "a candidate is never promoted to working email");
assert.equal(org.candidate, "candidate@example.org");
assert.equal(org.tab, "First call");
assert.equal(org.history[0].source, "csv-import");
assert.equal(org.history[0].effective, undefined, "do not fabricate outreach dates");
assert.equal(org.importSource.values.EIN, "01-2345678");
assert.equal((await call("/api/csv/import", payload)).data.added, 0, "retry preserves existing records");
assert.equal((await call("/api/csv/import", {...payload, text:text.replace("Fictional, Foundation", "Changed name")})).data.skipped, 2);
assert.equal(JSON.parse(db.prepare("SELECT profile FROM organizations WHERE id=?").bind("012345678").first().profile).name, org.name);
const badText = 'Organization,EIN,Working email\nValid,123456789,good@example.org\nInvalid,333333333,not-email';
const bad = {...payload, text:badText, mapping:autoMap(parseCSV(badText).headers)};
assert.equal((await call("/api/csv/preview", bad)).data.errors[0].row, 3);
assert.equal((await call("/api/csv/import", bad)).status, 400);
assert.equal(db.prepare("SELECT COUNT(*) AS n FROM organizations").first().n, 2, "invalid files must not import valid rows partially");
assert.equal((await call("/api/csv/import", {...payload,destination:"Meetings"})).status, 400);
assert.equal((await call("/api/csv/preview", {...payload,mapping:{...mapping,id:"0"}})).status, 400);
assert.equal((await call("/api/csv/preview", {...payload,mapping:{...mapping,email:"1000"}})).status, 400);
const dupeText = 'Organization,EIN\nA,555555555\nB,555555555';
const dup = {...payload,text:dupeText,mapping:autoMap(parseCSV(dupeText).headers)};
assert.equal((await call("/api/csv/preview", dup)).data.skipped, 1);
const race = await Promise.all([call("/api/csv/import",dup),call("/api/csv/import",dup)]);
assert.equal(race.reduce((n, r) => n+r.data.added, 0), 1);
res = await call("/api/csv/export", {ids:["012345678"]});
assert.equal(res.status, 200);
const exported = parseCSV(res.data);
assert.equal(exported.rows.length, 1);
assert.equal(exported.rows[0][exported.headers.indexOf("Person name")], "Test Person");
assert.equal(exported.rows[0][exported.headers.indexOf("Domain")], "example.org");
assert.ok(res.data.includes("'+15555550101"));
const formulas = csvDocument([["Safe"],["=HYPERLINK(1)"],[" @SUM(1)"],["\t+1"],["-1"],["012345678"]]);
assert.deepEqual(parseCSV(formulas).rows.map(r=>r[0]),["'=HYPERLINK(1)","' @SUM(1)","'\t+1","'-1","012345678"]);
assert.equal(transition(org, "Dial failed", "2002-11-02", "").status, "Contact review");
assert.equal(transition(org, "Not connected", "2099-11-02", "").step, "Cold call 2");
assert.equal(transition(org, "Do not contact", "2002-11-02", "").due, "");
db.close();
console.log("Passed CSV parsing, automatic mapping, preview, validation, duplicate/retry/race protection, import provenance, candidate separation, filtered export, formula neutralization and additional outcomes.");
